"""Wake's opt-in Hermes integration: setup, a manual journal CLI, and an optional nightly job."""
from pathlib import Path
import json
import os
import re
import subprocess
import sys
import tempfile
from datetime import datetime

ROOT = Path(__file__).resolve().parent
SCRIPT_NAME = 'wake_plugin_journal.py'
JOB_NAME = 'Wake nightly journal'
JOB_SKILL = 'wake-notes:journal'
DEFAULT_TIME = '00:30'
DEFAULT_DELIVERY = 'local'
TIME_RE = re.compile(r'^([01]?\d|2[0-3]):([0-5]\d)$')
DELIVERY_PLATFORMS = frozenset({
    'telegram', 'discord', 'slack', 'whatsapp', 'signal', 'matrix', 'mattermost',
    'dingtalk', 'feishu', 'wecom', 'wecom_callback', 'weixin', 'sms', 'email',
    'webhook', 'bluebubbles', 'qqbot', 'yuanbao',
})
JOB_PROMPT = (
    'Write the nightly Hermes journal for the day in the Script Output manifest. '
    'Use the wake-notes:journal skill and follow its Nightly run section exactly. '
    'Commit with the generated script. If it rejects the draft, fix exactly what it lists and retry. '
    'Reply with only the committed path and a one-line status, or the error.'
)

SCRIPT_TEMPLATE = '''#!/usr/bin/env python3
"""Wake nightly journal pre-run script (generated by `hermes wake-notes setup`).

Hermes cron runs this before the agent. `prepare` (the default) stages one
completed day and prints its manifest; when there is nothing to journal it
prints the Hermes wakeAgent gate so the agent never starts. `commit --day
YYYY-MM-DD` validates the draft the agent wrote and publishes it. `status` is
read-only.

Change the schedule or journal settings with `hermes wake-notes setup`; remove the job
with `hermes wake-notes unschedule`. Do not edit the journal, its state or the vault by
hand from an agent.
"""
import json
import os
import sys
from pathlib import Path

HOME = Path(os.environ.get("HERMES_HOME") or Path.home() / ".hermes")
FALLBACK_PLUGIN = Path(__WAKE_PLUGIN_ROOT__)


def _plugin_vendor():
    candidates = [HOME / "plugins" / "wake-notes", FALLBACK_PLUGIN]
    env_root = os.environ.get("WAKE_PLUGIN_ROOT")
    if env_root:
        candidates.insert(0, Path(env_root))
    for base in candidates:
        for vendor in (base / "vendor", base):
            if (vendor / "wake" / "__init__.py").is_file():
                return vendor
    raise SystemExit("Wake plugin not found; reinstall the plugin or rerun `hermes wake-notes setup`.")


def _settings():
    path = HOME / "wake" / "config.json"
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise SystemExit(f"Cannot read {path}: {exc}")
    if not isinstance(data, dict):
        raise SystemExit(f"Cannot read {path}: expected a JSON object")
    return data


def main(argv):
    argv = list(argv)
    action = "prepare"
    if argv and argv[0] in ("prepare", "commit", "status"):
        action = argv.pop(0)
    if action == "commit" and "--day" not in argv:
        print("commit requires --day YYYY-MM-DD", file=sys.stderr)
        return 2
    config = _settings()
    journal = config.get("journal") if isinstance(config.get("journal"), dict) else {}
    args = ["journal", "hermes", action]
    if "--timezone" not in argv and journal.get("timezone"):
        args += ["--timezone", str(journal["timezone"])]
    if "--vault" not in argv and config.get("vault"):
        args += ["--vault", str(config["vault"])]
    args += argv
    args += ["--no-sync"]
    os.environ.setdefault("HERMES_HOME", str(HOME))
    sys.path.insert(0, str(_plugin_vendor()))
    from wake.cli import main as wake_main
    return wake_main(args)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
'''


def run_wake(*args):
    bootstrap = "import runpy, sys; sys.path.insert(0, sys.argv.pop(1)); runpy.run_module('wake', run_name='__main__')"
    return subprocess.call([sys.executable, '-I', '-B', '-c', bootstrap, str(ROOT / 'vendor'), *args])


# ---- profile configuration -------------------------------------------------------------------
def _config_file():
    from hermes_constants import get_hermes_home
    return get_hermes_home() / 'wake' / 'config.json'


def _load_config():
    path = _config_file()
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise ValueError(f'cannot read {path}: {exc}') from exc
    if not isinstance(data, dict):
        raise ValueError(f'cannot read {path}: expected a JSON object')
    return data


def _atomic_write(path, text, mode=0o600):
    path = Path(path)
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(temp, mode)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def _write_config(data):
    _atomic_write(_config_file(), json.dumps(data, indent=2) + '\n')


def connected_vault():
    return _load_config().get('vault')


def connect_vault(path):
    vault = Path(path).expanduser().resolve()
    if not vault.is_dir() or not (vault / 'AGENTS.md').is_file() or not (vault / 'hot.md').is_file():
        raise ValueError('existing vault must contain AGENTS.md and hot.md')
    data = _load_config()
    data['vault'] = str(vault)
    _write_config(data)
    return str(vault)


# ---- schedule settings -----------------------------------------------------------------------
def default_timezone():
    """An IANA zone for the journal's day boundary, never a fixed UTC offset."""
    from zoneinfo import ZoneInfo
    wake_zone = (os.environ.get('WAKE_TIMEZONE') or '').strip()
    if wake_zone:
        try:
            ZoneInfo(wake_zone)
            return wake_zone
        except Exception:
            pass
    try:
        from hermes_time import get_timezone
        key = getattr(get_timezone(), 'key', None)
        if key:
            ZoneInfo(key)
            return key
    except Exception:
        pass
    tz_env = (os.environ.get('TZ') or '').strip()
    if tz_env:
        try:
            ZoneInfo(tz_env)
            return tz_env
        except Exception:
            pass
    try:
        value = Path('/etc/timezone').read_text(encoding='utf-8').strip()
        if value:
            ZoneInfo(value)
            return value
    except Exception:
        pass
    try:
        link = Path('/etc/localtime').resolve()
        marker = '/zoneinfo/'
        if marker in str(link):
            value = str(link).split(marker, 1)[1]
            ZoneInfo(value)
            return value
    except Exception:
        pass
    key = getattr(datetime.now().astimezone().tzinfo, 'key', None)
    if key:
        return key
    return 'UTC'


def validate_timezone(value):
    from zoneinfo import ZoneInfo, ZoneInfoNotFoundError
    value = value.strip()
    if not value:
        raise ValueError('timezone must be an IANA name such as Europe/Berlin')
    try:
        ZoneInfo(value)
    except ZoneInfoNotFoundError as exc:
        try:
            ZoneInfo('UTC')
        except ZoneInfoNotFoundError:
            raise ValueError('IANA timezone data is missing or incomplete; install your OS tzdata package or Python tzdata in the Hermes environment') from exc
        raise ValueError(f'{value!r} is not an IANA timezone, or its timezone data is missing') from exc
    except ValueError as exc:
        raise ValueError(f'{value!r} is not an IANA timezone ({exc})') from exc
    return value


def parse_time(value):
    match = TIME_RE.match(value.strip())
    if not match:
        raise ValueError('time must be HH:MM in 24-hour form')
    return int(match.group(1)), int(match.group(2))


def cron_expression(hour, minute):
    return f'{minute} {hour} * * *'


def validate_delivery(value):
    value = value.strip()
    if not value or len(value) > 200 or any(char.isspace() or ord(char) < 32 for char in value):
        raise ValueError('delivery must be local, origin, or a platform target')
    if value in ('local', 'origin'):
        return value
    head, _, target = value.partition(':')
    if head == 'bot-chat':
        return value
    if head not in DELIVERY_PLATFORMS or (':' in value and not target):
        raise ValueError('delivery must be local, origin, or a platform target such as telegram:12345')
    return value


# ---- cron job management ---------------------------------------------------------------------
def _is_journal_job(job):
    return (job.get('name') == JOB_NAME and job.get('script') == SCRIPT_NAME
            and job.get('skills') in ([JOB_SKILL], ['wake:journal']))


def managed_jobs():
    from cron.jobs import load_jobs
    config = _load_config()
    journal = config.get('journal') if isinstance(config.get('journal'), dict) else {}
    owned_id = journal.get('job_id')
    matches = [job for job in load_jobs() if owned_id and job.get('id') == owned_id]
    if any(not _is_journal_job(job) for job in matches):
        raise ValueError('saved journal job ID points to a different job; refusing to modify it')
    return matches


def _job_summary(job):
    return (f"{job.get('name')} ({job.get('id')}): schedule {job.get('schedule_display') or '?'}, "
            f"deliver {job.get('deliver') or '?'}, state {job.get('state') or '?'}")


def write_prerun_script():
    """Write the generated pre-run/commit shim, refusing to overwrite a user's file."""
    from hermes_constants import get_hermes_home
    path = get_hermes_home() / 'scripts' / SCRIPT_NAME
    content = SCRIPT_TEMPLATE.replace('__WAKE_PLUGIN_ROOT__', repr(str(ROOT)))
    if path.exists():
        existing = path.read_text(encoding='utf-8')
        if existing == content:
            return path
        raise FileExistsError(f'{path} exists with different content; not overwriting it. '
                              'Back it up and move it aside before retrying setup')
    _atomic_write(path, content, mode=0o700)
    return path


def _save_journal_settings(config, hour, minute, timezone, delivery):
    previous = _saved_journal(config)
    config['journal'] = {'time': f'{hour:02d}:{minute:02d}', 'timezone': timezone,
                         'delivery': delivery}
    if previous.get('job_id'):
        config['journal']['job_id'] = previous['job_id']
    _write_config(config)


def _scheduler_note():
    print('The job fires only while the Hermes cron scheduler is running '
          '(check `hermes cron status`).')


# ---- setup -----------------------------------------------------------------------------------
def _yes(prompt):
    return input(prompt).strip().lower() not in ('n', 'no')


def _default_no(prompt):
    return input(prompt).strip().lower() in ('y', 'yes')


def _saved_journal(config):
    saved = config.get('journal')
    return saved if isinstance(saved, dict) else {}


def _discover_model_providers():
    from hermes_cli.inventory import build_models_payload, load_picker_context
    payload = build_models_payload(load_picker_context(), include_unconfigured=False,
                                   for_picker=True, probe_custom_providers=False)
    return [row for row in payload.get('providers', [])
            if row.get('slug') and row.get('slug') != 'moa' and row.get('models')]


def _choose_journal_model():
    print('Model: [1] follow the configured cron/main model (default), [2] choose an available model')
    choice = input('Model choice [1]: ').strip() or '1'
    if choice == '1':
        return None, None
    if choice != '2':
        raise ValueError('Invalid model choice')
    try:
        providers = _discover_model_providers()
    except Exception as exc:
        raise ValueError(f'Could not discover models ({exc}); choose the default or retry') from exc
    if not providers:
        raise ValueError('No configured providers with listed models were found')
    print('Configured providers (listed models are not a guarantee of access):')
    for index, row in enumerate(providers, 1):
        print(f"  {index}. {row.get('name') or row.get('label') or row['slug']} ({row['slug']})")
    raw = input('Provider number: ').strip()
    if not raw.isdigit() or not 1 <= int(raw) <= len(providers):
        raise ValueError('Invalid provider choice')
    provider = providers[int(raw) - 1]
    models = [model for model in provider['models'] if isinstance(model, str) and model]
    if not models:
        raise ValueError('No models were listed for that provider')
    page = 0
    while True:
        start = page * 25
        for index, model in enumerate(models[start:start + 25], start + 1):
            print(f'  {index}. {model}')
        raw = input('Model number (n/p for next/previous page, q to cancel): ').strip().lower()
        if raw == 'n' and start + 25 < len(models):
            page += 1
        elif raw == 'p' and page:
            page -= 1
        elif raw.isdigit() and start < int(raw) <= min(start + 25, len(models)):
            return models[int(raw) - 1], provider['slug']
        else:
            raise ValueError('Model selection cancelled or invalid')


def _setup_schedule():
    try:
        config = _load_config()
    except ValueError as exc:
        print(f'Cannot read the Wake profile configuration: {exc}')
        return 1
    saved = _saved_journal(config)
    print()
    print('Nightly journal')
    print('  Hermes cron runs a pre-run script at the selected time. It stages one completed')
    print('  day from this profile\'s state.db and prints a manifest; when there is nothing to')
    print('  journal it skips the agent. Otherwise an agent follows the wake-notes:journal skill, writes')
    print('  only the draft, and the commit script validates, adds Evidence and publishes it.')
    print('  The agent runs with your host permissions: confinement is procedural, not an OS')
    print('  sandbox. Notes also go to the connected vault if one is set; nothing is git-synced.')
    print('  Fire time uses the Hermes scheduler timezone; the journal day boundary uses')
    print('  the separately selected timezone. Set the scheduler timezone to match if needed.')
    if not _yes('Schedule the nightly Hermes journal? [Y/n] '):
        print('No journal job created. Run `hermes wake-notes setup` again to add one.')
        return 0

    saved_time = saved.get('time') if isinstance(saved.get('time'), str) else DEFAULT_TIME
    try:
        parse_time(saved_time)
    except ValueError:
        saved_time = DEFAULT_TIME
    reply = input(f'Nightly time HH:MM [{saved_time}]: ').strip() or saved_time
    try:
        hour, minute = parse_time(reply)
    except ValueError as exc:
        print(f'Invalid time: {exc}. No journal job created.')
        return 1

    saved_zone = saved.get('timezone') if isinstance(saved.get('timezone'), str) else ''
    try:
        zone_default = validate_timezone(saved_zone) if saved_zone else default_timezone()
    except ValueError:
        zone_default = default_timezone()
    reply = input(f'IANA timezone for the journal day [{zone_default}]: ').strip() or zone_default
    try:
        timezone = validate_timezone(reply)
    except ValueError as exc:
        print(f'Invalid timezone: {exc}. No journal job created.')
        return 1

    saved_delivery = saved.get('delivery') if isinstance(saved.get('delivery'), str) else ''
    try:
        delivery_default = validate_delivery(saved_delivery) if saved_delivery else DEFAULT_DELIVERY
    except ValueError:
        delivery_default = DEFAULT_DELIVERY
    reply = input(f'Delivery (local, origin, or platform target) [{delivery_default}]: ').strip() or delivery_default
    try:
        delivery = validate_delivery(reply)
    except ValueError as exc:
        print(f'Invalid delivery: {exc}. No journal job created.')
        return 1

    try:
        model, provider = _choose_journal_model()
    except ValueError as exc:
        print(f'{exc}. No journal job created.')
        return 1

    if not config.get('vault'):
        if not _yes('No vault is connected; notes will stay in this profile\'s journal folder. Continue? [Y/n] '):
            print('No journal job created.')
            return 0

    try:
        from cron.jobs import load_jobs
        jobs = load_jobs()
    except (OSError, ValueError) as exc:
        print(f'Cannot read the cron store: {exc}. No journal job created.')
        return 1
    owned_id = saved.get('job_id')
    existing = [job for job in jobs if owned_id and job.get('id') == owned_id]
    if any(not _is_journal_job(job) for job in existing):
        print('Saved journal job ID points to a different job; refusing to modify it.')
        return 1
    if any(job.get('name') == JOB_NAME and job.get('id') != owned_id for job in jobs):
        print(f'A cron job named {JOB_NAME!r} already exists but was not created by this setup. '
              'Rename or remove it first; no journal job was created.')
        return 1
    if len(existing) > 1:
        print('Several Wake journal jobs already exist; no new job was created:')
        for job in existing:
            print('  ' + _job_summary(job))
        print('Remove duplicates with `hermes cron remove <id>`, then run setup again.')
        return 1

    if existing:
        job = existing[0]
        print('Existing Wake journal job: ' + _job_summary(job))
        selected_model = f'{model} via {provider}' if model else 'follow cron/main configuration'
        if not _default_no(f'Update it to {hour:02d}:{minute:02d} (scheduler timezone), '
                           f'day zone {timezone}, deliver {delivery}, model {selected_model}? [y/N] '):
            print(f"Existing Wake journal job {job.get('id')} left unchanged. No new job created.")
            return 0

    try:
        script = write_prerun_script()
    except (OSError, FileExistsError) as exc:
        print(f'Cannot create the pre-run script: {exc}. No journal job created.')
        return 1

    try:
        _save_journal_settings(config, hour, minute, timezone, delivery)
    except OSError as exc:
        print(f'Cannot save the journal settings: {exc}. No journal job created.')
        return 1

    from cron.jobs import create_job, update_job
    schedule = cron_expression(hour, minute)
    try:
        if existing:
            job = update_job(job['id'], {
                'schedule': schedule, 'deliver': delivery, 'prompt': JOB_PROMPT,
                'script': SCRIPT_NAME, 'skills': [JOB_SKILL], 'model': model, 'provider': provider,
            })
            print('Updated: Wake nightly journal')
        else:
            job = create_job(JOB_PROMPT, schedule, name=JOB_NAME, deliver=delivery,
                             script=SCRIPT_NAME, skills=[JOB_SKILL], model=model, provider=provider)
            print('Scheduled: Wake nightly journal')
    except (OSError, ValueError) as exc:
        print(f'Could not create or update the cron job: {exc}')
        return 1

    config['journal']['job_id'] = job['id']
    try:
        _write_config(config)
    except OSError as exc:
        print(f"Job {job['id']} exists but its ID could not be saved: {exc}. "
              f"Remove it with `hermes cron remove {job['id']}` before retrying.")
        return 1
    print(f"  Job:       {job.get('id')}")
    print(f'  Time:      {hour:02d}:{minute:02d} (Hermes scheduler timezone)')
    print(f'  Day zone:  {timezone}')
    print(f'  Delivery:  {delivery}')
    print(f'  Model:     {model} via {provider}' if model else '  Model:     follows cron/main configuration')
    print(f'  Script:    {script}')
    print(f'  Skill:     {JOB_SKILL}')
    print(f"  Remove:    hermes cron remove {job.get('id')}   (or: hermes wake-notes unschedule)")
    if not job.get('enabled'):
        print(f"  Note:      the existing job is paused; resume it with `hermes cron resume {job.get('id')}`")
    _scheduler_note()
    return 0


def unschedule():
    try:
        jobs = managed_jobs()
    except (OSError, ValueError) as exc:
        print(f'Cannot read the cron store: {exc}', file=sys.stderr)
        return 1
    if not jobs:
        print('No Wake journal job found.')
        return 0
    from cron.jobs import remove_job
    for job in jobs:
        if remove_job(job['id']):
            print(f"Removed Wake journal job {job.get('name')} ({job.get('id')}).")
        else:
            print(f"Could not remove Wake journal job {job.get('id')}.", file=sys.stderr)
            return 1
    print(f'The generated pre-run script remains in the profile scripts folder ({SCRIPT_NAME}); '
          'delete it if nothing else uses it.')
    return 0


def setup():
    if not sys.stdin.isatty():
        print('Wake setup requires an interactive terminal.', file=sys.stderr)
        return 1
    print('Wake setup: vault choices are optional; the nightly journal is offered by default.')
    if input('Create a new starter vault? [y/N] ').strip().lower() == 'y':
        path = input('New empty vault path: ').strip()
        if not path:
            print('No path supplied; vault not created.')
        elif input(f'Create starter files in {path!r} (no git commit)? [y/N] ').strip().lower() == 'y':
            result = run_wake('init', path, '--no-git')
            if result:
                return result
    if input('Show the human-authored manual journal steps? [y/N] ').strip().lower() == 'y':
        print('Run `hermes wake-notes journal prepare --no-sync`, then follow the bundled journal guide. '
              'No job is created by the manual workflow. See the plugin README.')
    if input('Connect an existing Wake vault and optionally install skills? [y/N] ').strip().lower() == 'y':
        path = input('Existing vault path: ').strip()
        if path and input(f'Connect {path!r} to this profile? [y/N] ').strip().lower() == 'y':
            try:
                vault = connect_vault(path)
            except (ValueError, OSError) as exc:
                print(f'Vault not connected: {exc}')
                return 1
            print(f'Connected vault: {vault}')
            if input('Install missing vault skills in this profile (no overwrite)? [y/N] ').strip().lower() == 'y':
                from hermes_constants import get_hermes_home
                skills = get_hermes_home() / 'skills'
                names = ('brain', 'brain-ingest', 'brain-lint')
                missing = [name for name in names if not (skills / name).exists()]
                status = run_wake('install-skills', '--hermes', '--vault', vault,
                                  *(arg for name in names for arg in ('--skill', name)))
                if status:
                    return status
                for name in missing:
                    skill = skills / name / 'SKILL.md'
                    if skill.is_file():
                        with skill.open('a', encoding='utf-8') as f:
                            f.write('\n## Hermes Wake profile connection\n\n'
                                    'For this Hermes profile, use the `vault` value in '
                                    '`$HERMES_HOME/wake/config.json` before the fallback paths above. '
                                    'If HERMES_HOME is unset, use `~/.hermes/wake/config.json`. '
                                    'Pass that path explicitly to helpers. If the connection is missing '
                                    'or invalid, ask the owner; do not guess another vault.\n')
    return _setup_schedule()


def configure_parser(parser):
    sub = parser.add_subparsers(dest='wake_action', required=True)
    sub.add_parser('setup', help='Choose optional vault setup; offers the nightly journal by default')
    sub.add_parser('unschedule', help='Remove the Wake nightly journal job created by setup')
    journal = sub.add_parser('journal', help='Run a manual Hermes journal step')
    journal.add_argument('action', choices=['prepare', 'commit', 'status'])
    journal.add_argument('--day')
    journal.add_argument('--timezone')
    journal.add_argument('--db')
    journal.add_argument('--journal')
    journal.add_argument('--vault')
    journal.add_argument('--no-sync', action='store_true', help='Accepted for compatibility; sync is always disabled')


def command(args):
    if args.wake_action == 'setup':
        try:
            return setup()
        except (EOFError, KeyboardInterrupt):
            print('\nSetup cancelled.')
            return 1
    if args.wake_action == 'unschedule':
        try:
            return unschedule()
        except (EOFError, KeyboardInterrupt):
            print('\nCancelled.')
            return 1
    opts = []
    for key in ('day', 'timezone', 'db', 'journal', 'vault'):
        value = getattr(args, key, None)
        if value is not None:
            opts += ['--' + key, value]
    if not getattr(args, 'vault', None):
        try:
            vault = connected_vault()
        except (OSError, ValueError) as exc:
            print(f'Cannot read connected vault: {exc}', file=sys.stderr)
            return 1
        if vault:
            opts += ['--vault', vault]
    return run_wake('journal', 'hermes', args.action, *opts, '--no-sync')


def register(ctx):
    ctx.register_cli_command(name='wake-notes', help='Optional Wake vault and journal',
                             setup_fn=configure_parser, handler_fn=command)
    register_skill = getattr(ctx, 'register_skill', None)
    skill = ROOT / 'skills' / 'journal' / 'SKILL.md'
    if callable(register_skill) and skill.is_file():
        register_skill('journal', skill,
                       description='Write the nightly Hermes journal from a staged manifest.')
